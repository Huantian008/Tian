/**
 * ============================================================
 * ACM-ICPC 区域赛级别算法题：三维接雨水 (Trapping Rain Water 3D)
 * ============================================================
 *
 * 题目描述：
 * ─────────
 * 给定一个 m × n 的矩阵 heightMap，表示一个三维地形图。
 * 矩阵中每个单元的高度为 heightMap[i][j]（非负整数）。
 *
 * 当下雨时（假设雨量无限），雨水会在地形的低洼处积聚。
 * 水可以在四个方向（上、下、左、右）上流动，遵循连通器原理 ——
 * 只要存在一条路径通向边界（或通向一个更低的外溢点），水就会流走。
 *
 * 换句话说，一个单元格 (i, j) 能存住的水量，取决于从该单元格出发、
 * 到达矩阵边界的所有路径中，路径上最大高度的最小值，再减去该单元格自身的高度。
 *
 * 请计算整个地形能接住的最大雨水总体积。
 *
 * 每个单元格的宽度和长度均为 1，因此一个单元格能存的水量在数值上等于
 * 水面高度减去单元格高度。
 *
 *
 * 输入格式：
 * ─────────
 * 第一行包含两个整数 m 和 n (1 ≤ m, n ≤ 200)，表示矩阵的行数和列数。
 * 接下来 m 行，每行 n 个整数，表示 heightMap[i][j] (0 ≤ heightMap[i][j] ≤ 20000)。
 *
 *
 * 输出格式：
 * ─────────
 * 输出一个整数，表示能接住的雨水总体积。
 *
 *
 * 样例输入 1：
 * ────────────
 * 3 6
 * 1 4 3 1 3 2
 * 3 2 1 3 2 4
 * 2 3 3 2 3 1
 *
 * 样例输出 1：
 * ────────────
 * 4
 *
 * 解释：
 * 积水位置示意（* 表示水）：
 *   1  4  3  1  3  2
 *   3  2  1  *  2  4
 *   2  3  3  2  3  1
 * 只有 (1,3) 这个位置能存 1 单位水，实际上有多处可以存水，
 * 总共 4 单位。
 *
 *
 * 样例输入 2：
 * ────────────
 * 5 5
 * 12 13  1 13 12
 * 13  4 13  2 13
 *  1 13  5 13  1
 * 13  2 13  4 13
 * 12 13  1 13 12
 *
 * 样例输出 2：
 * ────────────
 * 48
 *
 *
 * 样例输入 3：
 * ────────────
 * 3 3
 * 3 3 3
 * 3 1 3
 * 3 3 3
 *
 * 样例输出 3：
 * ────────────
 * 2
 *
 *
 * 数据范围与约定：
 * ───────────────
 * - 对于 30% 的数据：m, n ≤ 10
 * - 对于 60% 的数据：m, n ≤ 50
 * - 对于 100% 的数据：m, n ≤ 200, 0 ≤ heightMap[i][j] ≤ 20000
 *
 * 时间限制：2 秒
 * 内存限制：256 MB
 *
 *
 * ============================================================
 * 题解
 * ============================================================
 *
 * 【核心思路】
 * 这道题是 LeetCode 407 "Trapping Rain Water II" / POJ 2227 的原型，
 * 也是一道经典的 ACM 区域赛难度题目。
 *
 * 关键洞察：水会从最低的"缺口"流出去。
 *
 * 类比 1D 接雨水：我们用双指针，从左右两端向中间收缩，每次处理较矮的一侧。
 * 因为在 1D 中，"边界"只有左右两端。
 *
 * 推广到 2D：边界是整个矩阵的四条边。我们不知道水会从哪个方向流出去。
 * 但核心思想相同 —— 从最外围开始，用一个最小堆维护当前的"边界"，
 * 每次取出最矮的边界单元格，尝试向内部"扩展"。
 *
 * 【算法流程】
 *
 * 1. 初始化：
 *    - 将矩阵最外围的所有单元格加入一个最小堆（优先队列）。
 *    - 用一个 visited[m][n] 数组标记已访问的单元格（初始时外围标记为已访问）。
 *
 * 2. 扩展过程（类似 Prim / Dijkstra）：
 *    - 从堆中取出高度最小的单元格 (x, y)，其高度为 h。
 *    - 检查其四个邻居 (nx, ny)：
 *      a. 如果邻居未被访问：
 *         - 标记为已访问。
 *         - 如果邻居高度 < h，说明邻居比当前"水位"低，可以存水：
 *           water += h - heightMap[nx][ny]
 *         - 将邻居加入堆，其"有效高度"为 max(heightMap[nx][ny], h)
 *           （因为水的高度至少是当前边界高度）
 *
 * 3. 重复步骤 2 直到堆为空。
 *
 * 【为什么这是正确的？】
 *
 * 这本质上是 Dijkstra 算法在"最小最大高度"图上的应用。
 *
 * 定义：从单元格 u 到边界的一条路径的"瓶颈高度"为路径上所有单元格
 * 高度的最大值。单元格 u 的"水面高度"是所有到边界路径的瓶颈高度的最小值。
 *
 * 最小堆保证我们总是先处理水面高度最低的边界单元格，向外扩展时维护了
 * 这个"最小值"性质。这证明了贪心策略的正确性。
 *
 * 【复杂度分析】
 * - 时间复杂度：O(mn log(mn))
 *   - 每个单元格入堆一次、出堆一次
 *   - 堆操作 O(log(mn))
 * - 空间复杂度：O(mn)
 *   - visited 数组 O(mn)，堆 O(mn)
 *
 * 【扩展思考】
 * 如果允许水在 8 个方向流动？ —— 修改 directions 数组即可。
 * 如果某些单元格是"排水口"（水可以从内部流走）？—— 将这些排水口也加入初始堆。
 * 如果高度可以达到 10^9？—— 用 long long 存储水量。
 */


// ============================================================
// C++ 实现 (AC 代码)
// ============================================================

#include <iostream>
#include <vector>
#include <queue>
#include <algorithm>
using namespace std;

class Solution {
public:
    int trapRainWater(vector<vector<int>>& heightMap) {
        int m = heightMap.size();
        int n = heightMap[0].size();

        if (m < 3 || n < 3) return 0;  // 边界太小，无法存水

        // 最小堆：存储 {高度, 行, 列}
        // 使用 greater<pair> 实现最小堆
        priority_queue<
            pair<int, pair<int, int>>,
            vector<pair<int, pair<int, int>>>,
            greater<pair<int, pair<int, int>>>
        > minHeap;

        // visited 数组：用 vector<bool> 节省空间
        vector<vector<bool>> visited(m, vector<bool>(n, false));

        // 将所有边界单元格加入堆
        // 上下边界
        for (int j = 0; j < n; ++j) {
            visited[0][j] = true;
            minHeap.push({heightMap[0][j], {0, j}});
            visited[m - 1][j] = true;
            minHeap.push({heightMap[m - 1][j], {m - 1, j}});
        }
        // 左右边界（跳过角，避免重复）
        for (int i = 1; i < m - 1; ++i) {
            visited[i][0] = true;
            minHeap.push({heightMap[i][0], {i, 0}});
            visited[i][n - 1] = true;
            minHeap.push({heightMap[i][n - 1], {i, n - 1}});
        }

        // 四个方向：上、下、左、右
        const int dx[4] = {-1, 1, 0, 0};
        const int dy[4] = {0, 0, -1, 1};

        int totalWater = 0;
        int maxBoundaryHeight = 0;  // 当前扩展边界的最小高度

        while (!minHeap.empty()) {
            auto [height, pos] = minHeap.top();
            int x = pos.first;
            int y = pos.second;
            minHeap.pop();

            // 由于是 min-heap，每次取出的都是当前边界最矮的单元格
            // 这个高度就是从这个单元格向外扩展时，沿途单元格的水面高度下界
            maxBoundaryHeight = max(maxBoundaryHeight, height);

            // 向四个方向扩展
            for (int k = 0; k < 4; ++k) {
                int nx = x + dx[k];
                int ny = y + dy[k];

                // 检查边界和访问状态
                if (nx < 0 || nx >= m || ny < 0 || ny >= n || visited[nx][ny]) {
                    continue;
                }

                visited[nx][ny] = true;

                // 关键逻辑：
                // 邻居水面高度至少是 max(邻居自身高度, 当前水位)
                // 因为水必须经过至少高度为 height 的边界才能到达邻居
                int neighborHeight = heightMap[nx][ny];
                if (neighborHeight < height) {
                    // 邻居比当前水位低 → 可以存水
                    totalWater += height - neighborHeight;
                    // 存水后，这个位置的有效高度就是 height（水填到了这个高度）
                    minHeap.push({height, {nx, ny}});
                } else {
                    // 邻居比当前水位高 → 不能存水，但可能形成新的边界
                    minHeap.push({neighborHeight, {nx, ny}});
                }
            }
        }

        return totalWater;
    }
};


// ============================================================
// 本地测试
// ============================================================

int main() {
    Solution sol;

    // 测试用例 1
    vector<vector<int>> test1 = {
        {1, 4, 3, 1, 3, 2},
        {3, 2, 1, 3, 2, 4},
        {2, 3, 3, 2, 3, 1}
    };
    cout << "样例 1: " << sol.trapRainWater(test1) << " (期望: 4)" << endl;

    // 测试用例 2
    vector<vector<int>> test2 = {
        {12, 13,  1, 13, 12},
        {13,  4, 13,  2, 13},
        { 1, 13,  5, 13,  1},
        {13,  2, 13,  4, 13},
        {12, 13,  1, 13, 12}
    };
    cout << "样例 2: " << sol.trapRainWater(test2) << " (期望: 48)" << endl;

    // 测试用例 3：简单的"碗"形
    vector<vector<int>> test3 = {
        {3, 3, 3},
        {3, 1, 3},
        {3, 3, 3}
    };
    cout << "样例 3: " << sol.trapRainWater(test3) << " (期望: 2)" << endl;

    // 测试用例 4：一维情况（单行）
    vector<vector<int>> test4 = {
        {2, 0, 2}
    };
    cout << "样例 4 (单行, 3D中无法存水): " << sol.trapRainWater(test4) << " (期望: 0)" << endl;

    // 测试用例 5：更大的随机测试
    vector<vector<int>> test5 = {
        {5, 5, 5, 5, 5},
        {5, 1, 1, 1, 5},
        {5, 1, 5, 1, 5},
        {5, 1, 1, 1, 5},
        {5, 5, 5, 5, 5}
    };
    // 解释：中间 (1,1)~(1,3) 高1，被高5包围，水面高5，存4*3=12
    //       (2,1) 高1，水面高5，存4
    //       (2,3) 高1，水面高5，存4
    //       (3,1)~(3,3) 高1，水面高5，存4*3=12
    //       中间 (2,2) 高5，不存水
    //       共 12+4+4+12 = 32
    cout << "样例 5: " << sol.trapRainWater(test5) << " (期望: 32)" << endl;

    // 测试用例 6：平面（不能存水）
    vector<vector<int>> test6 = {
        {1, 1, 1},
        {1, 1, 1},
        {1, 1, 1}
    };
    cout << "样例 6 (平面): " << sol.trapRainWater(test6) << " (期望: 0)" << endl;

    // 测试用例 7：单峰（不能存水）
    vector<vector<int>> test7 = {
        {1, 1, 1, 1},
        {1, 9, 9, 1},
        {1, 9, 9, 1},
        {1, 1, 1, 1}
    };
    cout << "样例 7 (单峰): " << sol.trapRainWater(test7) << " (期望: 0)" << endl;

    return 0;
}
